/* eslint-disable @typescript-eslint/no-require-imports -- Standalone Node/Playwright verification script. */
const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('node:assert/strict');
const path = require('path');
const root = path.resolve(__dirname, '..');
const evidence = path.join(root, 'evidence');
fs.mkdirSync(evidence, { recursive: true });
const baseline = process.argv.includes('--baseline');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.setDefaultTimeout(20000);
  page.setDefaultNavigationTimeout(60000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle', timeout: 120000 });
    await page.waitForTimeout(1400);
    await page.screenshot({ path: path.join(evidence, baseline ? 'before-home.png' : 'desktop-home.png') });
    await page.goto('http://127.0.0.1:3000/login', { waitUntil: 'networkidle' });
    const authStyles = await page.locator('h2').first().evaluate(e => ({ font: getComputedStyle(e).fontFamily, color: getComputedStyle(e).color, background: getComputedStyle(document.body).backgroundColor }));
    if (baseline) fs.writeFileSync(path.join(evidence, 'auth-baseline.json'), JSON.stringify(authStyles, null, 2));
    else assert.deepEqual(authStyles, JSON.parse(fs.readFileSync(path.join(evidence, 'auth-baseline.json'))), 'Auth styling must stay identical');
    await page.screenshot({ path: path.join(evidence, baseline ? 'before-login.png' : 'after-login.png') });
    await page.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
    const header = await page.locator('header').evaluate(e => ({ height: e.getBoundingClientRect().height, bg: getComputedStyle(e).backgroundColor }));
    assert.equal(header.height, 70, 'Reference header must be 70px');
    assert.equal(header.bg, 'rgb(255, 255, 255)', 'Reference header must be white');
    if (baseline) return;
    const results = { header, authStyles, viewports: [], interactions: [] };
    assert.equal(await page.locator('a[href^="/services/"]').count(), 0, 'Do not link unimplemented service pages');
    await page.getByRole('button', { name: 'About us', exact: true }).hover();
    await page.waitForTimeout(350);
    await page.screenshot({ path: path.join(evidence, 'desktop-about-menu.png') });
    assert.equal(await page.locator('#nav-group-0').getAttribute('inert'), null);
    await page.getByRole('button', { name: 'About us', exact: true }).press('Escape');
    assert.notEqual(await page.locator('#nav-group-0').getAttribute('inert'), null);
    console.log('Interaction completed');
    results.interactions.push('Desktop hover and Escape dismissal');
    const cdp = await page.context().newCDPSession(page);
    await cdp.send('DOM.enable'); await cdp.send('CSS.enable');
    const doc = await cdp.send('DOM.getDocument');
    const node = await cdp.send('DOM.querySelector', { nodeId: doc.root.nodeId, selector: '.foundation-brand span' });
    results.renderedFont = await cdp.send('CSS.getPlatformFontsForNode', { nodeId: node.nodeId });
    assert.ok(results.renderedFont.fonts.some(f => f.isCustomFont), 'Roboto must render from a local file');
    for (const width of [390, 768, 991, 992, 1440]) {
      await page.setViewportSize({ width, height: width === 390 ? 844 : 900 });
      await page.waitForTimeout(100);
      const measure = await page.evaluate(() => ({ width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth,
        toggle: getComputedStyle(document.querySelector('.foundation-menu-toggle')).display,
        nav: getComputedStyle(document.querySelector('.foundation-nav')).display,
        headerHeight: document.querySelector('header').getBoundingClientRect().height,
        gridColumns: getComputedStyle(document.querySelector('.foundation-footer-grid')).gridTemplateColumns }));
      assert.equal(measure.overflow, false, `Overflow at ${width}`);
      assert.equal(measure.headerHeight, 70);
      assert.equal(measure.nav === 'none', width < 992);
      results.viewports.push(measure);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(evidence, 'mobile-home.png') });
    const toggle = page.locator('.foundation-menu-toggle');
    await toggle.click(); await page.waitForTimeout(350);
    const dialog = page.getByRole('dialog', { name: 'Site navigation' });
    assert.equal(await dialog.isVisible(), true);
    assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
    assert.equal(await page.locator('#marketing-content').evaluate(e => e.inert), true);
    await page.screenshot({ path: path.join(evidence, 'mobile-menu.png') });
    await dialog.getByRole('button', { name: 'About us', exact: true }).click();
    await page.screenshot({ path: path.join(evidence, 'mobile-about-expanded.png') });
    await dialog.getByRole('link', { name: 'Join', exact: true }).focus();
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Close navigation');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Join');
    await page.keyboard.press('Escape');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await toggle.evaluate(e => document.activeElement === e), true);
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
    console.log('Interaction completed');
    results.interactions.push('Mobile dialog, focus loop, Escape, focus restore and scroll lock');
    await toggle.click();
    await dialog.getByRole('button', { name: 'About us', exact: true }).click();
    await dialog.getByRole('link', { name: 'Life at TwinLink', exact: true }).click();
    await page.waitForURL('**/about#culture');
    await page.waitForTimeout(500);
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
    console.log('Interaction completed');
    results.interactions.push('Culture anchor navigation closes menu and restores scroll');
    await toggle.click(); await page.setViewportSize({ width: 992, height: 900 });
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    console.log('Interaction completed');
    results.interactions.push('Viewport switch closes mobile overlay');
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('http://127.0.0.1:3000/contact', { waitUntil: 'networkidle' });
    await page.screenshot({ path: path.join(evidence, 'desktop-contact.png') });
    await page.getByRole('textbox', { name: 'Your name' }).fill('Reference check');
    await page.getByRole('textbox', { name: 'Email', exact: true }).fill('check@example.com');
    await page.getByRole('textbox', { name: 'Your message' }).fill('Verify email draft only, without sending.');
    await page.getByRole('button', { name: 'Prepare email' }).click();
    assert.match(await page.getByRole('link', { name: 'Open email draft' }).getAttribute('href'), /^mailto:/);
    assert.match(await page.getByRole('status').innerText(), /not been sent/);
    console.log('Interaction completed');
    results.interactions.push('Contact form prepares a draft without delivery');
    await page.locator('#site-footer').scrollIntoViewIfNeeded();
    await page.locator('#site-footer').screenshot({ path: path.join(evidence, 'desktop-footer.png') });
    await page.getByRole('button', { name: 'Back to top' }).click();
    await page.waitForFunction(() => scrollY === 0, { timeout: 10000 });
    console.log('Interaction completed');
    results.interactions.push('Back to top');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(evidence, 'mobile-contact.png') });
    await page.locator('#site-footer').screenshot({ path: path.join(evidence, 'mobile-footer.png') });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
    const dots = page.getByRole('button', { name: /^Show slide/ });
    await dots.nth(2).click();
    assert.equal(await dots.nth(2).getAttribute('aria-current'), 'true');
    await page.waitForTimeout(5200);
    assert.equal(await dots.nth(2).getAttribute('aria-current'), 'true', 'Reduced motion must stop auto advance');
    await page.screenshot({ path: path.join(evidence, 'mobile-reduced-motion.png') });
    console.log('Interaction completed');
    results.interactions.push('Carousel dots and reduced-motion autoplay suppression');
    results.pageErrors = errors;
    assert.deepEqual(errors, [], 'No page exceptions');
    fs.writeFileSync(path.join(evidence, 'browser-results.json'), JSON.stringify(results, null, 2));
    console.log(JSON.stringify(results, null, 2));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
